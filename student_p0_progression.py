"""Evidence-gated automatic progression for LOCAL sandbox lessons only.

Public bounty submissions and formal human review remain separate gates.
Evidence is generated by upstream Aider and actual Foundry runs, never by a rubric.
"""
import argparse
import json
from pathlib import Path


def _verified_model_forge(record, expected_lesson, minimum_tests):
    if not isinstance(record, dict) or record.get("engine") != "upstream-aider-cli":
        return False
    if record.get("baseline_test_failing") is not True:
        return False
    if record.get("lesson") != expected_lesson or not record.get("endpoint_loopback"):
        return False
    if not record.get("reference_excluded_from_agent_workspace") or not record.get("real_model_invoked"):
        return False
    attempts = record.get("attempts")
    if not isinstance(attempts, list) or not attempts:
        return False
    return bool(any(
        a.get("edit_applied") is True
        and a.get("forge_executed") is True
        and a.get("forge_exit_code") == 0
        and a.get("forge_passed") is True
        and a.get("passing_tests", 0) >= minimum_tests
        and a.get("deterministic_fixes") == []
        for a in attempts if isinstance(a, dict)))


def evaluate(training, held_out):
    training_ok = _verified_model_forge(training, "reentrancy-01", 2)
    unseen_ok = _verified_model_forge(held_out, "held-out-access-control-01", 5)
    unseen_ok = bool(unseen_ok and held_out.get("unseen_fixture") is True
                     and held_out.get("authorization_verified") is True
                     and held_out.get("model_generated_patch") is True
                     and held_out.get("forge_passed") is True
                     and held_out.get("deterministic_fixes") == [])
    matching_model = bool(training.get("model") and training.get("model") == held_out.get("model"))
    passed = bool(training_ok and unseen_ok and matching_model)
    return {
        "training_model_only_passed": training_ok,
        "unseen_model_only_passed": unseen_ok,
        "same_local_model": matching_model,
        "local_training_progression_approved": passed,
        "unlocked_next_lesson": "access-control-01" if passed else None,
        "formal_course_graduated": False,
        "public_bounty_submission_approved": False,
        "reason": "Verified model-only Foundry success on training and separate unseen contract"
                  if passed else "Missing verified model-only training or unseen Foundry evidence",
    }


def write_result(training_file, held_out_file, output, memory=None):
    training = json.loads(Path(training_file).read_text(encoding="utf-8"))
    held_out = json.loads(Path(held_out_file).read_text(encoding="utf-8"))
    result = evaluate(training, held_out)
    output = Path(output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    if memory and result["local_training_progression_approved"]:
        path = Path(memory)
        state = json.loads(path.read_text(encoding="utf-8")) if path.exists() else {
            "version": 1, "sessions": [], "verified_courses": []}
        completed = state.setdefault("verified_courses", [])
        if "reentrancy-01" not in completed:
            completed.append("reentrancy-01")
        state.setdefault("sessions", []).append({
            "lesson": "reentrancy-01", "source": "local-p0-aider-independent-foundry",
            "evidence": [str(training_file), str(held_out_file)]})
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(state, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return result


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--training", required=True)
    p.add_argument("--held-out", required=True)
    p.add_argument("--output", required=True)
    p.add_argument("--memory")
    a = p.parse_args()
    print(json.dumps(write_result(a.training, a.held_out, a.output, a.memory), ensure_ascii=False))
